// Build a copyable error report for the publish failure
function buildErrorReport(
  pluginName: string,
  siteName: string,
  pluginId: number,
  siteId: number,
  errorMessage: string,
  stages: PublishStage[],
  logs: PublishLogEntry[]
): string {
  const timestamp = new Date().toISOString();
  const failedStage = stages.find(s => s.status === PublishStageStatusType.Error);

  const logLines = logs.map((l) => {
    const base = `[${l.timestamp}] [${l.level.toUpperCase()}] [${l.step}] ${l.message}`;
    if (!l.details || Object.keys(l.details).length === 0) return base;
    try {
      return `${base}\n  details=${Json.stringify(l.details)}`;
    } catch {
      return `${base}\n  details=[unserializable]`;
    }
  });

  const logSection = logs.length > 0
    ? `### Execution Logs\n\`\`\`\n${logLines.join("\n")}\n\`\`\`\n`
    : "";
  
  return `## Publish Error Report

**App:** WP Plugin Publish
**Timestamp:** ${timestamp}

### Context
- **Plugin:** ${pluginName} (Id: ${pluginId})
- **Site:** ${siteName} (Id: ${siteId})
- **Failed Stage:** ${failedStage?.label || "Unknown"}

### Error Message
\`\`\`
${errorMessage}
\`\`\`

### Stage Status
${stages.map(s => `- ${s.label}: ${s.status}${s.message ? ` - ${s.message}` : ""}`).join("\n")}

${logSection}
---
*Generated by WP Plugin Publish Error Reporter*`;
}

const STAGE_LABELS: Record<string, string> = {
  [PublishStageNameType.Backup]: "Creating Backup",
  [PublishStageNameType.RemoteBackup]: "Remote Backup",
  [PublishStageNameType.CloudUpload]: "Uploading to Cloud Storage",
  [PublishStageNameType.Package]: "Packaging Files",
  [PublishStageNameType.PreBackup]: "Pre-Upload Backup",
  [PublishStageNameType.Upload]: "Uploading to Site",
  [PublishStageNameType.Activate]: "Activating Plugin",
  [PublishStageNameType.Cleanup]: "Cleaning Up",
  [PublishStageNameType.Verify]: "Verifying Deployment",
  [PublishStageNameType.VersionCheck]: "Verifying Version",
};

// Stages visible in the progress UI (ordered).
// Internal/non-blocking stages (remote_backup, pre_backup) are excluded.
const VISIBLE_STAGE_ORDER = [
  PublishStageNameType.Backup, PublishStageNameType.CloudUpload, PublishStageNameType.Package, PublishStageNameType.Upload, PublishStageNameType.Activate, PublishStageNameType.VersionCheck,
];

function buildDefaultStages(): PublishStage[] {
  const stages: PublishStage[] = [
    { name: PublishStageNameType.Backup, label: STAGE_LABELS[PublishStageNameType.Backup], status: PublishStageStatusType.Pending },
  ];

  try {
    const saved = localStorage.getItem(LocalStorageKeyType.CloudStorageAccounts);
    if (saved) {
      const ids = Json.parse(saved) as number[];
      if (ids.length > 0) {
        stages.push({ name: PublishStageNameType.CloudUpload, label: STAGE_LABELS[PublishStageNameType.CloudUpload], status: PublishStageStatusType.Pending });
      }
    }
  } catch { /* ignore */ }

  stages.push(
    { name: PublishStageNameType.Package, label: STAGE_LABELS[PublishStageNameType.Package], status: PublishStageStatusType.Pending },
    { name: PublishStageNameType.Upload, label: STAGE_LABELS[PublishStageNameType.Upload], status: PublishStageStatusType.Pending },
    { name: PublishStageNameType.Activate, label: STAGE_LABELS[PublishStageNameType.Activate], status: PublishStageStatusType.Pending },
    { name: PublishStageNameType.VersionCheck, label: STAGE_LABELS[PublishStageNameType.VersionCheck], status: PublishStageStatusType.Pending },
  );

  return stages;
}

export function PublishProgressDialog({
  open,
  onOpenChange,
  pluginName,
  siteName,
  siteUrl,
  pluginId,
  siteId,
  onComplete,
}: PublishProgressDialogProps) {
  const { captureError, openErrorModal } = useErrorStore();
  const [stages, setStages] = useState<PublishStage[]>(buildDefaultStages);
  const [overallProgress, setOverallProgress] = useState(0);
  const [isComplete, setIsComplete] = useState(false);
  const [isSuccess, setIsSuccess] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [filesUpdated, setFilesUpdated] = useState<number | null>(null);
  const [backendStackTrace, setBackendStackTrace] = useState<string | null>(null);
  const [activeTab, setActiveTab] = useState<TabValueType>(TabValueType.Progress);
  
  // Version info
  const [localVersion, setLocalVersion] = useState<string | null>(null);
  const [remoteVersion, setRemoteVersion] = useState<string | null>(null);
  
  // Live logs
  const [logs, setLogs] = useState<PublishLogEntry[]>([]);
  
  // Refs to stabilize effect dependencies — these change every render but we don't want to re-subscribe
  const onCompleteRef = useRef(onComplete);
  onCompleteRef.current = onComplete;
  const pluginNameRef = useRef(pluginName);
  pluginNameRef.current = pluginName;
  const siteNameRef = useRef(siteName);
  siteNameRef.current = siteName;
  
  // Track whether this dialog session has completed — survives effect re-runs
  const publishCompletedRef = useRef(false);
  // Deduplicate logs — survives effect re-runs
  const seenLogKeysRef = useRef(new Set<string>());
  // Hold unsub functions so we can force-unsubscribe after completion
  const unsubsRef = useRef<Array<() => void>>([]);
  
  // Upload mode setting
  const [useFileByFile, setUseFileByFile] = useState(() => {
    const saved = localStorage.getItem(LocalStorageKeyType.Settings);
    if (saved) {
      try {
        const settings = Json.parse(saved);
        return settings.uploadMode === UploadModeType.FileByFile;
      } catch { /* ignore */ }
    }
    return true; // default to file-by-file
  });

  // Keep ZIP files setting
  const [keepZipFiles, setKeepZipFiles] = useState(() => {
    try {
      const saved = localStorage.getItem(LocalStorageKeyType.KeepZipFiles);
      return saved === "true";
    } catch {
      return false;
    }
  });

  // Helper: strip zipStructure from log details (it's huge and not useful in UI)
  const sanitizeLogDetails = (details?: LogEntryDetails): LogEntryDetails | undefined => {
    if (!details) return details;
    const { zipStructure, ...rest } = details;
    return Object.keys(rest).length > 0 ? rest : undefined;
  };

  const addLog = useCallback((log: PublishLogEntry) => {
    // Filter verbose ZIP file tree and package debug logs
    const msg = log.message.toLowerCase();
    if (log.level === 'debug' && log.step === 'package') return;
    if (log.step === 'file_list' || log.step === 'zip_contents') return;
    if (log.step === 'package' && (msg.includes('adding file') || msg.includes('compressing') || msg.includes('included in zip'))) return;
    
    // Deduplicate by timestamp + message
    const key = `${log.timestamp}|${log.step}|${log.message}`;
    if (seenLogKeysRef.current.has(key)) return;
    seenLogKeysRef.current.add(key);
    
    // Strip zipStructure from details
    setLogs(prev => [...prev, { ...log, details: sanitizeLogDetails(log.details) }]);
  }, []);

  // Force-unsubscribe all WS listeners
  const forceUnsubAll = useCallback(() => {
    unsubsRef.current.forEach(fn => fn());
    unsubsRef.current = [];
  }, []);

  // Reset state when dialog opens & fetch version info immediately
  useEffect(() => {
    if (open) {
      setStages(buildDefaultStages());
      setOverallProgress(0);
      setIsComplete(false);
      setIsSuccess(false);
      setErrorMessage(null);
      setFilesUpdated(null);
      setBackendStackTrace(null);
      setLogs([]);
      setActiveTab(TabValueType.Progress);
      setRemoteVersion(null);
      publishCompletedRef.current = false;
      seenLogKeysRef.current.clear();
      
      // Fetch version info
      if (pluginId && siteId) {
        api.previewPublish(pluginId, siteId).then(response => {
          if (response.success && response.data) {
            setLocalVersion(response.data.localVersion || null);
            setRemoteVersion(response.data.remoteVersion || null);
          }
        }).catch(() => {});
      }
    } else {
      // Dialog closed — force unsub everything
      forceUnsubAll();
    }
  }, [open, pluginId, siteId, forceUnsubAll]);

  // Listen for WebSocket events — deps are ONLY open/pluginId/siteId (stable values)
  useEffect(() => {
    if (!open) return;

    // Clean up any previous subscriptions first
    forceUnsubAll();

    const unsub1 = wsClient.on(WS_EVENTS.PUBLISH_STARTED, (data: unknown) => {
      const payload = data as { pluginId: number; siteId: number };
      if (payload.pluginId === pluginId && payload.siteId === siteId && !publishCompletedRef.current) {
        setStages(prev => prev.map(s => 
          s.name === PublishStageNameType.Backup ? { ...s, status: PublishStageStatusType.Running } : s
        ));
        addLog({
          timestamp: new Date().toISOString(),
          level: 'info',
          step: 'init',
          message: `Starting publish for ${pluginNameRef.current} to ${siteNameRef.current}`,
        });
      }
    });

    const unsub2 = wsClient.on(WS_EVENTS.PUBLISH_PROGRESS, (data: unknown) => {
      const payload = data as PublishProgressPayload;
      if (payload.pluginId === pluginId && payload.siteId === siteId && !publishCompletedRef.current) {
        // Use provided log OR generate a synthetic one from the progress message
        if (payload.log) {
          addLog(payload.log);
        } else if (payload.message) {
          addLog({
            timestamp: new Date().toISOString(),
            level: payload.status === "error" || payload.status === "failed" ? "error" : "info",
            step: payload.stage,
            message: payload.message,
          });
        }
        
        setStages(prev => {
          const currentStageIdx = VISIBLE_STAGE_ORDER.indexOf(payload.stage);
          return prev.map(s => {
            if (s.name === payload.stage) {
              let mappedStatus: PublishStageStatusType = PublishStageStatusType.Running;
              if (payload.status === PayloadStatusType.Success || payload.status === PayloadStatusType.Completed) mappedStatus = PublishStageStatusType.Success;
              else if (payload.status === PayloadStatusType.Error || payload.status === PayloadStatusType.Failed) mappedStatus = PublishStageStatusType.Error;
              return { ...s, status: mappedStatus, message: payload.message };
            }
            // Only auto-complete stages that appear BEFORE the current stage in the pipeline
            const stageIdx = VISIBLE_STAGE_ORDER.indexOf(s.name);
            if (s.status === PublishStageStatusType.Running && currentStageIdx > stageIdx && stageIdx >= 0) {
              return { ...s, status: PublishStageStatusType.Success };
            }
            return s;
          });
        });
        setOverallProgress(payload.progress);
      }
    });

    const unsub3 = wsClient.on(WS_EVENTS.PUBLISH_COMPLETE, (data: unknown) => {
      const payload = data as PublishCompletePayload & { status?: string; message?: string };
      if (payload.pluginId === pluginId && payload.siteId === siteId && !publishCompletedRef.current) {
        // PERMANENTLY lock — no more events accepted for this session
        publishCompletedRef.current = true;
        
        const wasSuccessful = payload.isSuccess ?? payload.success ?? (payload.status === PayloadStatusType.Completed || payload.status === PayloadStatusType.Success);
        
        setIsComplete(true);
        setIsSuccess(wasSuccessful);
        setFilesUpdated(payload.filesUpdated ?? null);
        setOverallProgress(100);
        
        if (payload.error || (payload.message && !wasSuccessful)) {
          setErrorMessage(payload.error || payload.message || "Unknown error");
        }
        if (payload.backendStackTrace) {
          setBackendStackTrace(payload.backendStackTrace);
        }
        
        if (payload.logs?.length) {
          payload.logs.forEach(l => addLog(l));
        }
        
        addLog({
          timestamp: new Date().toISOString(),
          level: wasSuccessful ? 'info' : 'error',
          step: 'complete',
          message: wasSuccessful 
            ? `Publish completed successfully (${payload.filesUpdated || 0} files updated)`
            : `Publish failed: ${payload.error || payload.message || 'Unknown error'}`,
        });
        
        // Force ALL stages to final state in a single setStages call
        const finalizeStages = (prev: PublishStage[]): PublishStage[] => {
          const base = payload.stages || prev;
          return base.map(s => {
            if (s.name === PublishStageNameType.VersionCheck) {
              return { ...s, status: PublishStageStatusType.Pending };
            }
            if (wasSuccessful && s.status !== PublishStageStatusType.Skipped) {
              return { ...s, status: PublishStageStatusType.Success };
            }
            if (!wasSuccessful && (s.status === PublishStageStatusType.Running || s.status === PublishStageStatusType.Pending)) {
              return { ...s, status: PublishStageStatusType.Error };
            }
            return s;
          });
        };
        setStages(finalizeStages);

        // IMMEDIATELY unsubscribe — no more WS events for this session
        forceUnsubAll();

        // Version verification (delayed, won't conflict since we use functional updater)
        if (wasSuccessful && pluginId && siteId) {
          setStages(prev => prev.map(s => 
            s.name === PublishStageNameType.VersionCheck ? { ...s, status: PublishStageStatusType.Running, message: "Checking remote version..." } : s
          ));
          api.previewPublish(pluginId, siteId).then(response => {
            if (response.success && response.data) {
              const newRemote = response.data.remoteVersion;
              const local = response.data.localVersion;
              setRemoteVersion(newRemote || null);
              setLocalVersion(local || null);
              
              const versionMatch = newRemote && local && newRemote === local;
              setStages(prev => prev.map(s => 
                s.name === PublishStageNameType.VersionCheck ? { 
                  ...s, 
                  status: versionMatch ? PublishStageStatusType.Success : PublishStageStatusType.Error,
                  message: versionMatch 
                    ? `Verified: v${newRemote} deployed` 
                    : `Version mismatch: remote=${newRemote || 'unknown'}, expected=${local}`
                } : s
              ));
              addLog({
                timestamp: new Date().toISOString(),
                level: versionMatch ? 'info' : 'warn',
                step: 'version_check',
                message: versionMatch
                  ? `✓ Version verified: remote is now v${newRemote}`
                  : `⚠ Version mismatch: remote=${newRemote || 'unknown'}, expected=${local}. OPcache may need flushing.`,
              });
            }
          }).catch(() => {
            setStages(prev => prev.map(s => 
              s.name === PublishStageNameType.VersionCheck ? { ...s, status: PublishStageStatusType.Skipped, message: "Could not verify" } : s
            ));
          });
        }

        onCompleteRef.current?.(wasSuccessful);
      }
    });

    // Listen for detailed log events (upload results, activate details, etc.)
    const unsub4 = wsClient.on(WS_EVENTS.LOG, (data: unknown) => {
      const payload = data as {
        pluginId?: number;
        siteId?: number;
        operationType?: string;
        log: {
          timestamp: string;
          level: string;
          step: string;
          message: string;
          details?: LogEntryDetails;
        };
      };
      if (
        payload.operationType === "publish" &&
        payload.pluginId === pluginId &&
        (payload.siteId === undefined || payload.siteId === siteId) &&
        !publishCompletedRef.current
      ) {
        addLog({ ...payload.log, level: payload.log.level as LogEntry["level"] });
      }
    });

    unsubsRef.current = [unsub1, unsub2, unsub3, unsub4];

    return () => {
      forceUnsubAll();
    };
  }, [open, pluginId, siteId, addLog, forceUnsubAll]);

  const getStageIcon = (stage: PublishStage) => {
    switch (stage.status) {
      case PublishStageStatusType.Success:
        return <Check className="h-4 w-4 text-primary" />;
      case PublishStageStatusType.Error:
        return <X className="h-4 w-4 text-destructive" />;
      case PublishStageStatusType.Running:
        return <div className="h-4 w-4 border-2 border-primary border-t-transparent rounded-full animate-spin" />;
      default:
        return <div className="h-4 w-4 rounded-full border-2 border-muted-foreground/30" />;
    }
  };

  const activeStageCount = stages.filter(s => s.status === PublishStageStatusType.Success || s.status === PublishStageStatusType.Running).length;
  const totalStages = stages.length;
  
  // Convert logs to BackendLogEntry format for error store
  const backendLogs: BackendLogEntry[] = logs.map(l => ({
    timestamp: l.timestamp,
    level: l.level,
    message: l.message,
    step: l.step,
    details: l.details,
  }));

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-2xl lg:max-w-3xl max-h-[90vh] flex flex-col overflow-hidden">
        <DialogHeader className="flex-shrink-0">
          <DialogTitle className="flex items-center gap-2">
            <Upload className="h-5 w-5 text-primary" />
            {isComplete ? (isSuccess ? "Publish Complete" : "Publish Failed") : "Publishing..."}
          </DialogTitle>
          <DialogDescription className="flex items-center gap-2 flex-wrap min-h-0">
            <span className="truncate">Deploying <strong>{pluginName}</strong> to <strong className="truncate max-w-[200px] inline-block align-bottom">{siteName}</strong></span>
            {localVersion ? (
              <span className="inline-flex items-center gap-1.5 text-xs flex-shrink-0">
                {/* Local version (NEW) — highlighted */}
                <Badge className="text-[10px] font-mono h-5 px-1.5 bg-primary text-primary-foreground font-bold">
                  v{localVersion}
                </Badge>
                <ArrowRight className="h-3 w-3 text-muted-foreground flex-shrink-0" />
                {/* Remote version (OLD) — subtle */}
                {remoteVersion ? (
                  <Badge variant="outline" className="text-[10px] font-mono h-5 px-1.5 text-muted-foreground">
                    v{remoteVersion}
                  </Badge>
                ) : (
                  <Badge variant="outline" className="text-[10px] italic text-muted-foreground h-5 px-1.5">
                    new install
                  </Badge>
                )}
              </span>
            ) : remoteVersion ? (
              <span className="inline-flex items-center gap-1.5 text-xs flex-shrink-0">
                <Badge variant="outline" className="text-[10px] font-mono h-5 px-1.5 text-muted-foreground">
                  v{remoteVersion}
                </Badge>
              </span>
            ) : (
              <span className="inline-flex items-center gap-1 text-xs text-muted-foreground flex-shrink-0">
                <div className="h-3 w-3 border border-muted-foreground/40 border-t-transparent rounded-full animate-spin" />
                loading...
              </span>
            )}
            {siteUrl && (
              <a 
                href={siteUrl} 
                target="_blank" 
                rel="noopener noreferrer"
                className="text-primary hover:underline inline-flex items-center gap-1 flex-shrink-0 ml-auto"
              >
                <ExternalLink className="h-3 w-3" />
                Open Site
              </a>
            )}
          </DialogDescription>
        </DialogHeader>

        {/* Tabbed content for better screen fit */}
        <Tabs value={activeTab} onValueChange={(val) => setActiveTab(val as TabValueType)} className="flex-1 flex flex-col overflow-hidden">
          <TabsList className="w-full flex flex-shrink-0">
            <TabsTrigger value={TabValueType.Progress} className="flex-1 gap-1 text-xs sm:text-sm">
              <ListChecks className="h-3 w-3" />
              Progress
            </TabsTrigger>
            <TabsTrigger value={TabValueType.Logs} className="flex-1 gap-1 text-xs sm:text-sm">
              <Terminal className="h-3 w-3" />
              Logs
              <Badge variant="secondary" className="ml-1 text-[10px]">{logs.length}</Badge>
            </TabsTrigger>
            <TabsTrigger value={TabValueType.Diagnostics} className="flex-1 gap-1 text-xs sm:text-sm">
              <Activity className="h-3 w-3" />
              Diag
            </TabsTrigger>
            <TabsTrigger value={TabValueType.Settings} className="flex-1 gap-1 text-xs sm:text-sm" disabled={isComplete}>
              <Settings2 className="h-3 w-3" />
              Settings
            </TabsTrigger>
          </TabsList>

          {/* Progress Tab */}
          <TabsContent value={TabValueType.Progress} className="flex-1 overflow-hidden mt-4">
            <ScrollArea className="h-full pr-4">
              <div className="space-y-4">
                {/* Overall Progress */}
                <div className="space-y-2">
                  <div className="flex justify-between text-sm">
                    <span className="text-muted-foreground">
                      Stage {Math.min(activeStageCount + 1, totalStages)} of {totalStages}
                    </span>
                    <span className="font-medium">{isComplete ? 100 : Math.round(overallProgress)}%</span>
                  </div>
                  <Progress value={isComplete ? 100 : overallProgress} className="h-2" />
                </div>

                {/* Stage List */}
                <div className="space-y-2">
                  {stages.map((stage) => (
                    <div
                      key={stage.name}
                      className={cn(
                        "flex items-center gap-3 p-3 rounded-lg border transition-colors",
                        stage.status === PublishStageStatusType.Running && "border-primary bg-primary/5",
                        stage.status === PublishStageStatusType.Success && "border-primary/30 bg-primary/5",
                        stage.status === PublishStageStatusType.Error && "border-destructive bg-destructive/5",
                        stage.status === PublishStageStatusType.Pending && "border-border opacity-60"
                      )}
                    >
                      {getStageIcon(stage)}
                      <div className="flex-1 min-w-0">
                        <div className="flex items-center gap-2">
                          <p className="text-sm font-medium">{stage.label}</p>
                          {/* Show local version on deploy stages, remote on version_check */}
                          {stage.name !== PublishStageNameType.VersionCheck && localVersion && stage.status !== PublishStageStatusType.Pending && (
                            <Badge className="text-[10px] font-mono h-4 px-1.5 bg-primary/80 text-primary-foreground">
                              v{localVersion}
                            </Badge>
                          )}
                          {stage.name === PublishStageNameType.VersionCheck && remoteVersion && stage.status !== PublishStageStatusType.Pending && (
                            <Badge variant="outline" className="text-[10px] font-mono h-4 px-1.5 border-accent text-accent-foreground">
                              v{remoteVersion}
                              <span className="ml-1 text-muted-foreground font-normal">server</span>
                            </Badge>
                          )}
                        </div>
                        {stage.message && (
                          <p className="text-xs text-muted-foreground truncate">
                            {stage.message}
                          </p>
                        )}
                      </div>
                      {stage.status === PublishStageStatusType.Success && (
                        <Badge variant="outline" className="text-xs text-primary border-primary/30 flex-shrink-0">
                          Done
                        </Badge>
                      )}
                      {stage.status === PublishStageStatusType.Error && (
                        <Badge variant="outline" className="text-xs text-destructive border-destructive/30 flex-shrink-0">
                          Failed
                        </Badge>
                      )}
                    </div>
                  ))}
                </div>

                {/* Success Message */}
                {isComplete && isSuccess && filesUpdated !== null && (
                  <div className="rounded-lg border border-primary/30 bg-primary/5 p-4">
                    <div className="flex items-center gap-2">
                      <Check className="h-5 w-5 text-primary" />
                      <span className="font-medium">
                        Successfully published {filesUpdated} files
                      </span>
                    </div>
                    {siteUrl && (
                      <a 
                        href={siteUrl} 
                        target="_blank" 
                        rel="noopener noreferrer"
                        className="mt-2 inline-flex items-center gap-1 text-sm text-primary hover:underline"
                      >
                        <ExternalLink className="h-3 w-3" />
                        Open {siteName}
                      </a>
                    )}
                  </div>
                )}

                {/* Error Message */}
                {isComplete && isSuccess === false && errorMessage && (
                  <div className="rounded-lg border border-destructive/30 bg-destructive/5 p-4 space-y-3">
                    <div className="flex items-start gap-2">
                      <AlertCircle className="h-5 w-5 text-destructive mt-0.5 flex-shrink-0" />
                      <div className="flex-1 min-w-0">
                        <p className="font-medium text-destructive">Publish Failed</p>
                        <p className="text-sm text-muted-foreground mt-1 break-words">{errorMessage}</p>
                      </div>
                    </div>
                    
                    <div className="flex gap-2 pt-2 border-t border-destructive/20">
                      <Button
                        variant="outline"
                        size="sm"
                        className="text-xs"
                        onClick={() => {
                          const report = buildErrorReport(pluginName, siteName, pluginId, siteId, errorMessage, stages, logs);
                          navigator.clipboard.writeText(report);
                          toast.success("Error report copied to clipboard");
                        }}
                      >
                        <Copy className="h-3 w-3 mr-1" />
                        Copy Error
                      </Button>
                      <Button
                        variant="outline"
                        size="sm"
                        className="text-xs text-destructive hover:text-destructive"
                        onClick={() => {
                          const failedStage = stages.find(s => s.status === PublishStageStatusType.Error);
                          const captured = captureError(
                            {
                              code: "E9001",
                              message: errorMessage,
                              details: `Failed during stage: ${failedStage?.label || "Unknown"}`,
                              timestamp: new Date().toISOString(),
                            },
                            {
                              endpoint: `/plugins/${pluginId}/sites/${siteId}/publish`,
                              method: "POST",
                              context: {
                                source: "PublishProgressDialog.onComplete",
                                triggerComponent: "PublishProgressDialog",
                                triggerAction: "publish_failed",
                                pluginId,
                                pluginName,
                                siteId,
                                siteName,
                                failedStage: failedStage?.name,
                                stageStatuses: stages.map(s => ({ name: s.name, status: s.status, message: s.message })),
                                backendLogFiles: {
                                  log: "data/errors/log.txt",
                                  errorLog: "data/errors/error.log.txt",
                                },
                              },
                              backendLogs,
                              backendStackTrace: backendStackTrace || undefined,
                              siteUrl,
                            }
                          );
                          openErrorModal(captured);
                        }}
                      >
                        <ExternalLink className="h-3 w-3 mr-1" />
                        View Details
                      </Button>
                    </div>
                  </div>
                )}
              </div>
            </ScrollArea>
          </TabsContent>

          {/* Logs Tab — verbose logs already filtered at accumulation */}
          <TabsContent value={TabValueType.Logs} className="flex-1 overflow-hidden mt-4">
            <LogViewer
              logs={logs}
              title="Execution Logs"
              height="h-[300px]"
              showToggle={false}
              emptyMessage="Waiting for publish to start..."
              className="h-full"
            />
          </TabsContent>

          {/* Diagnostics Tab */}
          <TabsContent value={TabValueType.Diagnostics} className="flex-1 overflow-hidden mt-4">
            <ActivationDiagnostics logs={logs} className="h-full" />
          </TabsContent>

          {/* Settings Tab */}
          <TabsContent value={TabValueType.Settings} className="flex-1 overflow-hidden mt-4">
            <div className="space-y-4">
              <div className="flex items-center justify-between p-4 bg-muted/50 rounded-lg">
                <div>
                  <Label htmlFor="upload-mode" className="text-sm font-medium">
                    Upload Mode
                  </Label>
                  <p className="text-xs text-muted-foreground mt-1">
                    ZIP uploads the entire plugin as one file. File-by-file uploads changed files individually.
                  </p>
                </div>
                <div className="flex items-center gap-2">
                  <span className={cn("text-xs", !useFileByFile && "text-primary font-medium")}>ZIP</span>
                  <Switch
                    id="upload-mode"
                    checked={useFileByFile}
                    onCheckedChange={(checked) => {
                      setUseFileByFile(checked);
                      const saved = localStorage.getItem(LocalStorageKeyType.Settings);
                      const settings = saved ? Json.parse(saved) : {};
                      settings.uploadMode = checked ? UploadModeType.FileByFile : UploadModeType.Zip;
                      localStorage.setItem(LocalStorageKeyType.Settings, Json.stringify(settings));
                      toast.success(`Upload mode: ${checked ? "File-by-file" : "ZIP"}`);
                    }}
                  />
                  <span className={cn("text-xs", useFileByFile && "text-primary font-medium")}>File-by-file</span>
                </div>
              </div>

              <div className="flex items-center justify-between p-4 bg-muted/50 rounded-lg">
                <div>
                  <Label htmlFor="keep-zip" className="text-sm font-medium">
                    Keep ZIP Files
                  </Label>
                  <p className="text-xs text-muted-foreground mt-1">
                    Preserve ZIP files in temp folder after publish (for debugging).
                  </p>
                </div>
                <Switch
                  id="keep-zip"
                  checked={keepZipFiles}
                  onCheckedChange={(checked) => {
                    setKeepZipFiles(checked);
                    localStorage.setItem(LocalStorageKeyType.KeepZipFiles, String(checked));
                    toast.success(`Keep ZIP files: ${checked ? "enabled" : "disabled"}`);
                  }}
                />
              </div>
            </div>
          </TabsContent>
        </Tabs>

        <DialogFooter className="flex-shrink-0 pt-4 border-t">
          <Button
            variant={isComplete ? "default" : "outline"}
            onClick={() => onOpenChange(false)}
          >
            {isComplete ? "Done" : "Close"}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
